CALIBRATIONS: str = FULL_CALIBRATIONS


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent,
        help="output directory (default: this file's directory)",
    )
    parser.add_argument(
        "--profile",
        choices=("full", "mini"),
        default="full",
        help="'full' = the 13-taxon accuracy benchmark; "
        "'mini' = the 10-taxon quick-start dataset written to examples/",
    )
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument(
        "--include-ml-tree",
        action="store_true",
        help="also (re)generate tree_ml.nwk with IQ-TREE 2; requires iqtree2 on PATH",
    )
    args = parser.parse_args(argv)

    select_profile(args.profile)

    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    targets = {
        "tree.nwk": None,
        "alignment.fasta": None,
        "truth.yaml": None,
        "calibrations.yaml": CALIBRATIONS,
    }
    if not args.force:
        existing = [name for name in targets if (out / name).exists()]
        if existing:
            print(
                f"refusing to overwrite {', '.join(existing)} (use --force)",
                file=sys.stderr,
            )
            return 2

    newick_tree = build_tree()
    newick = to_newick(newick_tree)
    nodes = node_table(newick_tree)
    sequences = simulate_alignment(newick_tree, ALIGNMENT_LENGTH, SEED)

    missing = [leaf for leaf in LEAVES if leaf not in sequences]
    if missing:
        raise RuntimeError(f"simulation lost tips: {missing}")

    (out / "tree.nwk").write_text(newick + "\n", encoding="utf-8")
    write_fasta(sequences, out / "alignment.fasta", LEAVES)
    (out / "truth.yaml").write_text(truth_document(nodes), encoding="utf-8")
    (out / "calibrations.yaml").write_text(CALIBRATIONS, encoding="utf-8")

    total = tree_length(newick_tree)
    print(f"wrote 4 files to {out}")
    print(f"  taxa={len(LEAVES)} alignment_length={ALIGNMENT_LENGTH} seed={SEED}")
    print(f"  root age={TOPOLOGY['root'][1]} Ma  tree length={total:.6f} subs/site")

    if args.include_ml_tree:
        write_ml_tree_variant(out, newick)
    return 0


def write_ml_tree_variant(out: Path, newick: str) -> None:
    """Estimate ML branch lengths with IQ-TREE 2 and write ``tree_ml.nwk``.

    The topology is held fixed (``-te``) so that the only difference from
    ``tree.nwk`` is branch-length estimation error, which is the quantity under
    test. IQ-TREE 2 returns an unrooted tree, so it is re-rooted at the midpoint
    of the branch leading to ``Dog`` - the rooting used by the simulated truth.
    """
    import shutil
    import subprocess
    import tempfile

    iqtree = shutil.which("iqtree2") or shutil.which("iqtree")
    if not iqtree:
        raise SystemExit("--include-ml-tree needs iqtree2 (or iqtree) on PATH")

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        shutil.copy2(out / "alignment.fasta", work / "alignment.fasta")
        (work / "tree.nwk").write_text(newick + "\n", encoding="utf-8")
        subprocess.run(
            [
                iqtree,
                "-s",
                "alignment.fasta",
                "-te",
                "tree.nwk",
                "-m",
                "GTR+G",
                "-pre",
                "ml",
                "-quiet",
                "-redo",
            ],
            cwd=str(work),
            check=True,
            capture_output=True,
            text=True,
            timeout=3600,
        )
        estimated = (work / "ml.treefile").read_text(encoding="utf-8")

    import dendropy

    tree = dendropy.Tree.get(data=estimated, schema="newick", preserve_underscores=True)
    dog = tree.taxon_namespace.get_taxon("Dog")
    leaf = next(n for n in tree.leaf_nodes() if n.taxon is dog)
    edge_length = leaf.edge.length or 0.0
    tree.reroot_at_edge(leaf.edge, length1=edge_length / 2.0, length2=edge_length / 2.0)
    tree.is_rooted = True
    text = tree.as_string("newick").strip()
    if not text.endswith(";"):
        text += ";"
    (out / "tree_ml.nwk").write_text(text + "\n", encoding="utf-8")
    print("  wrote tree_ml.nwk (ML branch lengths, GTR+G, topology fixed)")


if __name__ == "__main__":
    raise SystemExit(main())
